/* =====================================================
   DETECT CATEGORY
===================================================== */

export function detectCategoryLocal(name = "", generic = "") {
  // Combine both
  const haystack = `${name} ${generic}`.toLowerCase();

  for (const [category, keywords] of Object.entries(LOCAL_CATEGORY_RULES)) {
    for (const keyword of keywords) {
      if (haystack.includes(keyword.toLowerCase())) {
        return category;
      }
    }
  }
  return "Other";
}